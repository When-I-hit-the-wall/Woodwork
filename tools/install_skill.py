"""Assembles the user's Claude skill «woodwork-report» and installs it (spec 2026-11-16-skill-woodwork-report-et-simple-report).

    python tools/install_skill.py                 writes ~/.claude/skills/woodwork-report/
    python tools/install_skill.py --dest <dir>    writes <dir>/woodwork-report/ instead
    python tools/install_skill.py --check         says whether ~/.claude/skills/woodwork-report/ (or --dest) is what this script would write
    python tools/install_skill.py --zip <file>    writes the skill into a zip (a folder woodwork-report/ at its root) to upload to claude.ai, Plugins > Skills; installs nothing

The skill is written once, in `skill/woodwork-report/SKILL.md`; everything else in it is a copy made here, never by hand: `assets/woodwork/` is `woodwork/`, `assets/sheets/` is `sheets/`, `assets/templates/` is `templates/`, `references/commands.md` is `docs/typst/commands.md`, and `references/catalog.md` is computed from `source/sheets/` through `tools/generate.py`. The version written into SKILL.md is `woodwork-version` of `woodwork/woodwork.typ`. An installed copy, or an uploaded zip, does not follow the repository: run this script again after a change (decisions D-23, D-25).
"""

import argparse
import re
import shutil
import sys
import zipfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import generate  # noqa: E402

ROOT = generate.ROOT
NAME = "woodwork-report"
SKILL = ROOT / "skill" / NAME
VERSION_MARK = "@WOODWORK_VERSION@"
COPIES = {"assets/woodwork": ROOT / "woodwork", "assets/sheets": ROOT / "sheets", "assets/templates": ROOT / "templates"}
VERSION = re.compile(r'^#let woodwork-version = "([^"]+)"', re.M)
VAR = re.compile(r'#var\("([^"]+)", ([-0-9.]+), "([^"]*)"')
HEADING = re.compile(r"^= (.+)$", re.M)


def default_dest():
    """~/.claude/skills -- on Windows, Path.home() reads USERPROFILE."""
    return Path.home() / ".claude" / "skills"


def woodwork_version():
    found = VERSION.search((ROOT / "woodwork" / "woodwork.typ").read_text(encoding="utf-8"))
    if found is None:
        raise SystemExit("woodwork/woodwork.typ: no `#let woodwork-version = \"…\"` line")
    return found.group(1)


def catalog():
    """references/catalog.md: one row per check of source/sheets/, its title and files in each language and the values a user changes."""
    _, paths = generate.load_labels()
    out = generate.plan()
    src = generate.SOURCE / "sheets"
    lines = ["# Catalogue of the checks", "",
             "Generated by `tools/install_skill.py` from Woodwork's sheets. Paths are relative to `assets/sheets/<lang>/`. «Values» are the ones a standard sheet declares with a number: change them to the user's; every other value is read from `woodwork/data/`.", ""]
    family = None
    for f in sorted(p for p in src.rglob("*.typ") if not p.stem.endswith("-detailed")):
        rel = f.relative_to(src)
        if rel.parts[0] != family:
            family = rel.parts[0]
            lines += ["## " + family, "", "| Check | fr | de | en | Values |", "|---|---|---|---|---|"]
        files = {lang: generate.target_of(rel, lang, paths).as_posix() for lang in generate.LANGS}
        detailed = rel.with_name(rel.stem + "-detailed" + rel.suffix)
        has_detailed = (src / detailed).exists()
        text = out[ROOT / "sheets" / "en" / files["en"]].decode("utf-8")
        title = HEADING.search(text).group(1)
        values = ", ".join("`%s` %s %s" % (k, v, u) for k, v, u in VAR.findall(text))
        cells = []
        for lang in generate.LANGS:
            cell = "`%s`" % files[lang]
            if has_detailed:
                cell += " · `%s`" % generate.target_of(detailed, lang, paths).as_posix()
            cells.append(cell)
        lines.append("| %s | %s | %s |" % (title, " | ".join(cells), values))
    lines += ["", "The second file of a cell is the detailed sheet: text, a figure and the derivation of the material's values, with the same utilisation.", ""]
    return "\n".join(lines).encode("utf-8")


def assemble():
    """{path relative to the skill's folder: bytes} -- the whole skill, as it is installed."""
    files = {}
    skill_md = (SKILL / "SKILL.md").read_text(encoding="utf-8")
    if VERSION_MARK not in skill_md:
        raise SystemExit("skill/%s/SKILL.md: no %s to stamp" % (NAME, VERSION_MARK))
    files["SKILL.md"] = skill_md.replace(VERSION_MARK, woodwork_version()).encode("utf-8")
    for p in sorted(SKILL.rglob("*")):
        rel = p.relative_to(SKILL).as_posix()
        if p.is_file() and rel != "SKILL.md":
            files[rel] = p.read_bytes()
    files["references/commands.md"] = (ROOT / "docs" / "typst" / "commands.md").read_bytes()
    files["references/catalog.md"] = catalog()
    for prefix, tree in COPIES.items():
        for p in sorted(tree.rglob("*")):
            if p.is_file():
                files["%s/%s" % (prefix, p.relative_to(tree).as_posix())] = p.read_bytes()
    return files


def differences(files, folder):
    """What `folder` lacks or holds otherwise than `files`, and what it holds beyond them."""
    diff = []
    for rel, data in files.items():
        p = folder / rel
        if not p.exists():
            diff.append("missing " + rel)
        elif p.read_bytes() != data:
            diff.append("differs " + rel)
    if folder.exists():
        for p in folder.rglob("*"):
            if p.is_file() and p.relative_to(folder).as_posix() not in files:
                diff.append("extra " + p.relative_to(folder).as_posix())
    return sorted(diff)


def install(dest):
    """Writes the skill to dest/woodwork-report/, replacing what an earlier install left there; returns that folder."""
    folder = Path(dest) / NAME
    if folder.name != NAME:
        raise SystemExit("refusing to replace %s: not a folder named %s" % (folder, NAME))
    files = assemble()
    if folder.exists():
        shutil.rmtree(folder)
    for rel, data in files.items():
        p = folder / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(data)
    return folder


def write_zip(path):
    """Writes the skill into the zip `path`, every file under woodwork-report/, as claude.ai's upload of a skill expects; returns the path."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(path, "w", compression=zipfile.ZIP_DEFLATED) as z:
        for rel, data in assemble().items():
            z.writestr("%s/%s" % (NAME, rel), data)
    return path


def main(argv=None):
    parser = argparse.ArgumentParser(description="Install the Claude skill woodwork-report.")
    parser.add_argument("--dest", type=Path, default=None, help="the skills folder (default: ~/.claude/skills)")
    parser.add_argument("--check", action="store_true", help="compare the installed skill with what would be written")
    parser.add_argument("--zip", type=Path, default=None, metavar="FILE", help="write the skill into this zip, for claude.ai, instead of installing it")
    args = parser.parse_args(argv)
    if args.zip is not None:
        path = write_zip(args.zip)
        print("woodwork-report %s written to %s (%d kB): upload it in claude.ai, Plugins > Skills > Add" % (woodwork_version(), path, path.stat().st_size // 1024))
        return 0
    dest = args.dest if args.dest is not None else default_dest()
    if args.check:
        diff = differences(assemble(), dest / NAME)
        for line in diff:
            print(line)
        print("%s is %s" % (dest / NAME, "up to date" if not diff else "out of date: python tools/install_skill.py"))
        return 1 if diff else 0
    folder = install(dest)
    print("woodwork-report %s installed in %s" % (woodwork_version(), folder))
    return 0


if __name__ == "__main__":
    sys.exit(main())
